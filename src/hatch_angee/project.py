"""Round-trip-safe ownership of the generated addon dependency group."""

from __future__ import annotations

import os
import tempfile
from collections.abc import Iterable
from pathlib import Path

import tomlkit
from tomlkit.exceptions import ParseError
from tomlkit.items import Comment, InlineTable, Table, Whitespace

GENERATED_COMMENT = "GENERATED by hatch-angee from the enabled addons' manifests — do not edit"
_LEGACY_GENERATED_COMMENT = "GENERATED by angee build from the enabled addons' manifests — do not edit"


class ProjectError(ValueError):
    """A pyproject error that identifies both the file and the failing key."""

    def __init__(self, path: Path, key: str, message: str) -> None:
        self.path = path
        self.key = key
        self.message = message
        super().__init__(f"{path}: {key}: {message}")


def write_block(pyproject_path: Path | str, deps: Iterable[str]) -> None:
    """Write only ``[dependency-groups].addons`` and its generated header.

    tomlkit retains comments, whitespace, key order, and every unrelated value.
    Exactly one header comment survives, directly above the generated key —
    orphaned or duplicated headers, including the retired CLI wording, are reclaimed. A
    byte-identical result is not written again, making repeated builds a true
    no-op; changed results replace the file atomically (temp file +
    ``os.replace``) so a concurrent reader never sees a truncated manifest.
    """

    path = Path(pyproject_path)
    try:
        original = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as error:
        raise ProjectError(path, "file", str(error)) from error
    try:
        document = tomlkit.parse(original)
    except ParseError as error:
        raise ProjectError(path, "toml", str(error)) from error

    groups = document.get("dependency-groups")
    if isinstance(groups, InlineTable):
        raise ProjectError(
            path,
            "dependency-groups",
            "is an inline table; rewrite it as a standard [dependency-groups] table"
            " so the generated addons group can carry its header",
        )
    if groups is not None and not isinstance(groups, Table):
        raise ProjectError(path, "dependency-groups", "must be a table")

    generated = tomlkit.array().multiline(True)
    for dependency in sorted(set(deps)):
        generated.append(dependency)

    # Rebuild the table through the public API only (raw body surgery desyncs
    # tomlkit's key index): copy every entry that is not ours — each item keeps
    # its own trivia/comments — dropping the addons key and any header comment
    # (orphans and duplicates included), then append exactly one header and the
    # generated key. The generated key always renders last in the table.
    body = groups.value.body if groups is not None else []
    # tomlkit stores the separator before a following table in this table's
    # body, so hold that whitespace back until the generated block is complete.
    tail_start = len(body)
    while (
        tail_start
        and body[tail_start - 1][0] is None
        and isinstance(body[tail_start - 1][1], Whitespace)
    ):
        tail_start -= 1

    rebuilt = tomlkit.table()
    for key, item in body[:tail_start]:
        if key is None and isinstance(item, Comment) and any(
            header in item.as_string() for header in (GENERATED_COMMENT, _LEGACY_GENERATED_COMMENT)
        ):
            continue
        if key is not None and key.key == "addons":
            continue
        if key is None:
            if isinstance(item, (Comment, Whitespace)):
                rebuilt.add(item)
        else:
            rebuilt.add(key, item)
    rebuilt.add(tomlkit.comment(GENERATED_COMMENT))
    rebuilt.add("addons", generated)
    for _, item in body[tail_start:]:
        assert isinstance(item, Whitespace)
        rebuilt.add(item)
    document["dependency-groups"] = rebuilt

    rendered = tomlkit.dumps(document)
    if rendered == original:
        return
    descriptor, tmp_name = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.", suffix=".tmp")
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write(rendered)
        os.replace(tmp_name, path)
    finally:
        Path(tmp_name).unlink(missing_ok=True)
